// ============ Strict decoding ============

/// Decode one signed envelope: valid UTF-8, no duplicate keys, nesting at most 64 deep, no unknown
/// fields, no trailing value (the reference `Decode`).
pub fn decode(data: &[u8]) -> Result<SignedReceipt> {
    let text = std::str::from_utf8(data)
        .map_err(|e| Error(format!("decode signed outcome receipt: invalid UTF-8: {e}")))?;
    let mut scanner = serde_json::Deserializer::from_str(text);
    serde::de::DeserializeSeed::deserialize(
        Scan {
            path: "$".into(),
            depth: 0,
        },
        &mut scanner,
    )
    .map_err(|e| Error(format!("decode signed outcome receipt: {e}")))?;
    scanner
        .end()
        .map_err(|_| Error("decode signed outcome receipt: trailing JSON value".into()))?;
    serde_json::from_str(text).map_err(|e| Error(format!("decode signed outcome receipt: {e}")))
}

/// Walks any JSON value, failing on a duplicate object key or nesting deeper than the reference
/// allows (it fails at depth > 64 with the root at 0).
struct Scan {
    path: String,
    depth: usize,
}

impl<'de> serde::de::DeserializeSeed<'de> for Scan {
    type Value = ();
    fn deserialize<D: serde::Deserializer<'de>>(self, d: D) -> std::result::Result<(), D::Error> {
        if self.depth > MAX_DEPTH {
            return Err(serde::de::Error::custom("JSON nesting exceeds 64 levels"));
        }
        d.deserialize_any(self)
    }
}

impl<'de> serde::de::Visitor<'de> for Scan {
    type Value = ();
    fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("any JSON value")
    }
    fn visit_bool<E>(self, _: bool) -> std::result::Result<(), E> {
        Ok(())
    }
    fn visit_i64<E>(self, _: i64) -> std::result::Result<(), E> {
        Ok(())
    }
    fn visit_u64<E>(self, _: u64) -> std::result::Result<(), E> {
        Ok(())
    }
    fn visit_f64<E>(self, _: f64) -> std::result::Result<(), E> {
        Ok(())
    }
    fn visit_str<E>(self, _: &str) -> std::result::Result<(), E> {
        Ok(())
    }
    fn visit_unit<E>(self) -> std::result::Result<(), E> {
        Ok(())
    }
    fn visit_seq<A: serde::de::SeqAccess<'de>>(self, mut seq: A) -> std::result::Result<(), A::Error> {
        let mut i = 0usize;
        while seq
            .next_element_seed(Scan {
                path: format!("{}[{i}]", self.path),
                depth: self.depth + 1,
            })?
            .is_some()
        {
            i += 1;
        }
        Ok(())
    }
    fn visit_map<A: serde::de::MapAccess<'de>>(self, mut map: A) -> std::result::Result<(), A::Error> {
        let mut seen = HashSet::new();
        while let Some(key) = map.next_key::<String>()? {
            if !seen.insert(key.clone()) {
                return Err(serde::de::Error::custom(format!(
                    "{} contains duplicate key {key:?}",
                    self.path
                )));
            }
            map.next_value_seed(Scan {
                path: format!("{}.{key}", self.path),
                depth: self.depth + 1,
            })?;
        }
        Ok(())
    }
}

// ============ Time: RFC 3339 as the reference parses and prints it ============

/// An instant in UTC as (seconds since the Unix epoch, nanoseconds), plus whether it was written
/// with `Z`. Only `Z` counts as UTC: the reference rejects any numeric offset, `+00:00` included.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Instant {
    secs: i64,
    nanos: u32,
}

fn days_in_month(year: i64, month: u32) -> u32 {
    match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        _ if (year % 4 == 0 && year % 100 != 0) || year % 400 == 0 => 29,
        _ => 28,
    }
}

// Days from 1970-01-01 to the given civil date (proleptic Gregorian; Howard Hinnant's algorithm).
fn days_from_civil(y: i64, m: u32, d: u32) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (m as i64 + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d as i64 - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146097 + doe - 719468
}

fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719468;
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = z - era * 146097;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

fn digits(s: &[u8]) -> Option<i64> {
    if s.is_empty() || !s.iter().all(u8::is_ascii_digit) {
        return None;
    }
    Some(s.iter().fold(0i64, |acc, c| acc * 10 + i64::from(c - b'0')))
}

/// Parse a timestamp the way the reference's JSON decoding does: `YYYY-MM-DDThh:mm:ss`, an hour of
/// one or two digits, an optional fraction after `.` or `,` (digits past the ninth are dropped), then
/// `Z` or a `+hh:mm`/`-hh:mm` offset. Lowercase `t` or `z` and a leap second are rejected, as there.
/// Returns the instant and whether it is in UTC (written with `Z`).
pub fn parse_time(field: &str, s: &str) -> Result<(Instant, bool)> {
    let b = s.as_bytes();
    let bad = || Error(format!("{field}: cannot parse time {s:?}"));
    if b.len() < 11 || b[4] != b'-' || b[7] != b'-' || b[10] != b'T' {
        return Err(bad());
    }
    let year = digits(&b[0..4]).ok_or_else(bad)?;
    let month = digits(&b[5..7]).ok_or_else(bad)? as u32;
    let day = digits(&b[8..10]).ok_or_else(bad)? as u32;
    let mut i = 11;
    let hour_len = if b.get(12) == Some(&b':') { 1 } else { 2 };
    let hour = digits(b.get(i..i + hour_len).ok_or_else(bad)?).ok_or_else(bad)?;
    i += hour_len;
    if b.get(i) != Some(&b':') {
        return Err(bad());
    }
    let minute = digits(b.get(i + 1..i + 3).ok_or_else(bad)?).ok_or_else(bad)?;
    if b.get(i + 3) != Some(&b':') {
        return Err(bad());
    }
    let second = digits(b.get(i + 4..i + 6).ok_or_else(bad)?).ok_or_else(bad)?;
    i += 6;
    let mut nanos = 0u32;
    if matches!(b.get(i), Some(b'.') | Some(b',')) && b.get(i + 1).is_some_and(u8::is_ascii_digit) {
        let start = i + 1;
        let mut end = start;
        while end < b.len() && b[end].is_ascii_digit() {
            end += 1;
        }
        let frac = &b[start..end.min(start + 9)];
        nanos = frac.iter().fold(0u32, |acc, c| acc * 10 + u32::from(c - b'0'))
            * 10u32.pow(9 - frac.len() as u32);
        i = end;
    }
    if !(1..=12).contains(&month)
        || day < 1
        || day > days_in_month(year, month)
        || hour > 23
        || minute > 59
        || second > 59
    {
        return Err(Error(format!("{field}: time {s:?} is out of range")));
    }
    let local = days_from_civil(year, month, day) * 86400 + hour * 3600 + minute * 60 + second;
    let (secs, utc) = match &b[i..] {
        b"Z" => (local, true),
        [sign @ (b'+' | b'-'), h1, h2, b':', m1, m2] => {
            let h = digits(&[*h1, *h2]).ok_or_else(bad)?;
            let m = digits(&[*m1, *m2]).ok_or_else(bad)?;
            if h > 23 || m > 59 {
                return Err(bad());
            }
            let offset = (h * 60 + m) * 60;
            (
                if *sign == b'+' {
                    local - offset
                } else {
                    local + offset
                },
                false,
            )
        }
        _ => return Err(bad()),
    };
    Ok((Instant { secs, nanos }, utc))
}

/// The reference's JSON form of a UTC time: RFC 3339 with the fraction's trailing zeros trimmed.
pub fn format_time(t: Instant) -> String {
    let days = t.secs.div_euclid(86400);
    let rem = t.secs.rem_euclid(86400);
    let (y, m, d) = civil_from_days(days);
    let mut out = format!(
        "{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}",
        rem / 3600,
        rem % 3600 / 60,
        rem % 60
    );
    if t.nanos > 0 {
        let frac = format!("{:09}", t.nanos);
        out.push('.');
        out.push_str(frac.trim_end_matches('0'));
    }
    out.push('Z');
    out
}

// The reference's zero time (0001-01-01T00:00:00Z) counts as missing.
const ZERO_TIME: Instant = Instant {
    secs: -62135596800,
    nanos: 0,
};

fn utc_time(field: &str, s: &str) -> Result<Instant> {
    let (t, utc) = parse_time(field, s)?;
    if t == ZERO_TIME {
        fail!("{field} is required");
    }
    if !utc {
        fail!("{field} must be expressed in UTC");
    }
    Ok(t)
}

// ============ Field rules (the reference's patterns, without a regex engine) ============

fn validate_hash(field: &str, v: &str) -> Result<()> {
    if v.len() != 64
        || !v
            .bytes()
            .all(|c| c.is_ascii_digit() || (b'a'..=b'f').contains(&c))
    {
        fail!("{field} must be a lowercase 64-character SHA-256 hex digest");
    }
    Ok(())
}

fn validate_id(field: &str, v: &str) -> Result<()> {
    let b = v.as_bytes();
    let rest_ok = b
        .iter()
        .skip(1)
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'.' | b'_' | b':' | b'-'));
    if b.is_empty() || b.len() > 128 || !b[0].is_ascii_alphanumeric() || !rest_ok {
        fail!("{field} must be 1-128 ASCII identifier characters");
    }
    Ok(())
}

fn validate_text(field: &str, v: &str) -> Result<()> {
    if v.trim().is_empty() {
        fail!("{field} is required");
    }
    if v.len() > MAX_TEXT_FIELD_BYTES {
        fail!("{field} exceeds {MAX_TEXT_FIELD_BYTES} bytes");
    }
    if !unicode_normalization::is_nfc(v) {
        fail!("{field} must be NFC-normalized");
    }
    if v.chars().any(|c| (c as u32) < 0x20 || c as u32 == 0x7f) {
        fail!("{field} contains a forbidden control character");
    }
    Ok(())
}

fn validate_decimal(field: &str, v: &str) -> Result<()> {
    let body = v.strip_prefix('-').unwrap_or(v);
    let (int, frac) = match body.split_once('.') {
        Some((i, f)) => (i, Some(f)),
        None => (body, None),
    };
    let int_ok =
        int == "0" || (!int.is_empty() && !int.starts_with('0') && int.bytes().all(|c| c.is_ascii_digit()));
    let frac_ok = frac.is_none_or(|f| !f.is_empty() && f.bytes().all(|c| c.is_ascii_digit()));
    if !int_ok || !frac_ok {
        fail!("{field} must be a canonical decimal string");
    }
    // As the reference has it. The "-0." prefix also rejects real values in (-1, 0) such as "-0.25";
    // "-0.0" alone is already caught by the trailing-zero rule below. Kept for parity (see tests).
    if v == "-0" || v.starts_with("-0.") {
        fail!("{field} must not represent negative zero");
    }
    if frac.is_some() && v.ends_with('0') {
        fail!("{field} must not contain trailing fractional zeroes");
    }
    Ok(())
}

fn validate_id_set(field: &str, values: &[String]) -> Result<()> {
    let mut seen = HashSet::new();
    for (i, v) in values.iter().enumerate() {
        validate_id(&format!("{field}[{i}]"), v)?;
        if !seen.insert(v) {
            fail!("{field} contains duplicate value {v:?}");
        }
    }
    Ok(())
}

fn validate_memory_ref(prefix: &str, m: &MemoryRef) -> Result<()> {
    validate_id(&format!("{prefix}.chain_id"), &m.chain_id)?;
    validate_id(&format!("{prefix}.memory_id"), &m.memory_id)?;
    validate_hash(&format!("{prefix}.content_hash"), &m.content_hash)?;
    validate_text(&format!("{prefix}.domain"), &m.domain)?;
    if validate_hash("", &m.author_agent_id).is_err() {
        fail!("{prefix}.author_agent_id must be a lowercase 32-byte Ed25519 public key");
    }
    if m.classification != 0 {
        fail!("{prefix}.classification must be 0 (PUBLIC) in v1");
    }
    Ok(())
}

// ============ Validation (the reference `Validate`) ============

/// The parsed times of a valid receipt, used by the canonical encoder.
#[derive(Debug, Clone, Copy)]
pub struct Times {
    pub created_at: Instant,
    pub started_at: Instant,
    pub completed_at: Instant,
}

/// Enforce the v1 evidence contract. Does not check signatures; see [`verify_envelope`].
pub fn validate(r: &Receipt) -> Result<Times> {
    if r.version != VERSION_V1 {
        fail!("version must be {VERSION_V1:?}");
    }
    let created_at = utc_time("created_at", &r.created_at)?;
    validate_text("producer.name", &r.producer.name)?;
    validate_text("producer.version", &r.producer.version)?;
    validate_hash("producer.implementation_hash", &r.producer.implementation_hash)?;

    validate_id("task_set.id", &r.task_set.id)?;
    validate_text("task_set.version", &r.task_set.version)?;
    validate_hash("task_set.digest", &r.task_set.digest)?;
    if r.task_set.tasks.is_empty() {
        fail!("task_set.tasks must contain at least one task");
    }
    if r.task_set.digest != task_set_digest(&r.task_set.tasks) {
        fail!("task_set.digest does not match the canonical task list");
    }
    let mut task_ids = HashSet::new();
    for (i, t) in r.task_set.tasks.iter().enumerate() {
        let prefix = format!("task_set.tasks[{i}]");
        validate_memory_ref(&prefix, t)?;
        if !task_ids.insert(t.memory_id.as_str()) {
            fail!("{prefix} duplicates memory_id {:?}", t.memory_id);
        }
    }
    validate_memory_ref("candidate", &r.candidate)?;
    if task_ids.contains(r.candidate.memory_id.as_str()) {
        fail!("candidate memory must not also be a task memory");
    }

    let e = &r.evaluation;
    validate_text("evaluation.judge.model_id", &e.judge.model_id)?;
    for (name, v) in [
        ("evaluation.judge.model_hash", &e.judge.model_hash),
        ("evaluation.judge.rubric_hash", &e.judge.rubric_hash),
        ("evaluation.judge.prompt_hash", &e.judge.prompt_hash),
        ("evaluation.judge.environment_hash", &e.judge.environment_hash),
    ] {
        validate_hash(name, v)?;
    }
    validate_id("evaluation.retrieval.id", &e.retrieval.id)?;
    validate_text("evaluation.retrieval.version", &e.retrieval.version)?;
    if !(1..=1000).contains(&e.retrieval.top_k) {
        fail!("evaluation.retrieval.top_k must be between 1 and 1000");
    }
    validate_text("evaluation.metric", &e.metric)?;
    validate_text("evaluation.unit", &e.unit)?;
    if e.repeats < 1 {
        fail!("evaluation.repeats must be at least 1");
    }
    let started_at = utc_time("evaluation.started_at", &e.started_at)?;
    let completed_at = utc_time("evaluation.completed_at", &e.completed_at)?;
    if completed_at < started_at {
        fail!("evaluation.completed_at must not precede started_at");
    }
    if created_at < completed_at {
        fail!("created_at must not precede evaluation.completed_at");
    }
    if r.runs.is_empty() {
        fail!("runs must not be empty");
    }
    validate_runs(r, &task_ids)?;
    let expected_pairs = r.task_set.tasks.len() as i64 * e.repeats;
    validate_summary(&r.summary, expected_pairs)?;
    if r.summary.status != STATUS_FAILED {
        if let Some(i) = r.runs.iter().position(|run| !run.error.is_empty()) {
            fail!(
                "runs[{i}] records an error but summary.status is {:?}",
                r.summary.status
            );
        }
    }
    if r.evidence.is_empty() {
        fail!("evidence must contain at least one artifact");
    }
    let mut digests = HashSet::new();
    for (i, ev) in r.evidence.iter().enumerate() {
        let prefix = format!("evidence[{i}]");
        validate_id(&format!("{prefix}.kind"), &ev.kind)?;
        validate_text(&format!("{prefix}.media_type"), &ev.media_type)?;
        validate_hash(&format!("{prefix}.digest"), &ev.digest)?;
        if !ev.uri.is_empty() {
            validate_text(&format!("{prefix}.uri"), &ev.uri)?;
        }
        if !digests.insert(ev.digest.as_str()) {
            fail!("{prefix} duplicates evidence digest {:?}", ev.digest);
        }
    }
    for (i, c) in r.caveats.iter().enumerate() {
        validate_text(&format!("caveats[{i}]"), c)?;
    }
    Ok(Times {
        created_at,
        started_at,
        completed_at,
    })
}

/// One task/trial pair's arms: (control, treatment).
type Arms<'a> = (Option<&'a Run>, Option<&'a Run>);

fn validate_runs(r: &Receipt, task_ids: &HashSet<&str>) -> Result<()> {
    let candidate = r.candidate.memory_id.as_str();
    let mut pairs: HashMap<(&str, i64), Arms> = HashMap::new();
    for (i, run) in r.runs.iter().enumerate() {
        let prefix = format!("runs[{i}]");
        if !task_ids.contains(run.task_memory_id.as_str()) {
            fail!(
                "{prefix}.task_memory_id {:?} is not in task_set.tasks",
                run.task_memory_id
            );
        }
        if run.trial < 1 || run.trial > r.evaluation.repeats {
            fail!("{prefix}.trial must be between 1 and evaluation.repeats");
        }
        if run.arm != ARM_CONTROL && run.arm != ARM_TREATMENT {
            fail!("{prefix}.arm must be {ARM_CONTROL:?} or {ARM_TREATMENT:?}");
        }
        validate_hash(&format!("{prefix}.query_hash"), &run.query_hash)?;
        validate_id_set(&format!("{prefix}.context_memory_ids"), &run.context_memory_ids)?;
        validate_id_set(&format!("{prefix}.masked_memory_ids"), &run.masked_memory_ids)?;
        if let Some(id) = run
            .masked_memory_ids
            .iter()
            .find(|id| run.context_memory_ids.contains(id))
        {
            fail!("{prefix} cannot both include and mask memory {id:?}");
        }
        let present = run.context_memory_ids.iter().any(|id| id == candidate);
        let masked = run.masked_memory_ids.iter().any(|id| id == candidate);
        if run.arm == ARM_TREATMENT {
            if !present {
                fail!("{prefix} treatment context must include the candidate memory");
            }
            if masked {
                fail!("{prefix} treatment must not mask the candidate memory");
            }
        } else {
            if present {
                fail!("{prefix} control context must not include the candidate memory");
            }
            if !masked {
                fail!("{prefix} control must record the candidate in masked_memory_ids");
            }
        }
        if run.score.is_empty() && run.passed.is_none() && run.error.is_empty() {
            fail!("{prefix} must carry score, passed, or error");
        }
        if !run.score.is_empty() {
            validate_decimal(&format!("{prefix}.score"), &run.score)?;
        }
        if run.latency_micros < 0 {
            fail!("{prefix}.latency_micros must not be negative");
        }
        let mut artifacts = HashSet::new();
        for (j, a) in run.artifact_hashes.iter().enumerate() {
            validate_hash(&format!("{prefix}.artifact_hashes[{j}]"), a)?;
            artifacts.insert(a);
        }
        if artifacts.len() != run.artifact_hashes.len() {
            fail!("{prefix}.artifact_hashes contains duplicates");
        }
        let slot = pairs.entry((run.task_memory_id.as_str(), run.trial)).or_default();
        let (arm_slot, arm) = if run.arm == ARM_CONTROL {
            (&mut slot.0, "control")
        } else {
            (&mut slot.1, "treatment")
        };
        if arm_slot.is_some() {
            fail!("{prefix} duplicates the {arm} arm for task/trial");
        }
        *arm_slot = Some(run);
    }
    let expected = r.task_set.tasks.len() as i64 * r.evaluation.repeats;
    if pairs.len() as i64 != expected {
        fail!("runs contain {} task/trial pairs, want {expected}", pairs.len());
    }
    let mut keys: Vec<_> = pairs.keys().copied().collect();
    keys.sort();
    for key in keys {
        let (task, trial) = key;
        let (Some(control), Some(treatment)) = pairs[&key] else {
            fail!("task {task:?} trial {trial} must contain one control and one treatment run");
        };
        if control.query_hash != treatment.query_hash {
            fail!("task {task:?} trial {trial} arms must use the same query_hash");
        }
        if control.seed != treatment.seed {
            fail!("task {task:?} trial {trial} arms must use the same seed");
        }
        let (without, removed) = remove_first(&treatment.context_memory_ids, candidate);
        if !removed || control.context_memory_ids != without {
            fail!("task {task:?} trial {trial} treatment must equal the control context plus the candidate");
        }
        let (mut control_masks, had) = remove_first(&control.masked_memory_ids, candidate);
        let mut treatment_masks = treatment.masked_memory_ids.clone();
        control_masks.sort();
        treatment_masks.sort();
        if !had || control_masks != treatment_masks {
            fail!("task {task:?} trial {trial} masked memories must differ only by the candidate");
        }
    }
    Ok(())
}

fn remove_first(values: &[String], target: &str) -> (Vec<String>, bool) {
    let mut removed = false;
    let out = values
        .iter()
        .filter(|v| {
            if !removed && v.as_str() == target {
                removed = true;
                false
            } else {
                true
            }
        })
        .cloned()
        .collect();
    (out, removed)
}

fn validate_summary(s: &Summary, expected_pairs: i64) -> Result<()> {
    if !STATUSES.contains(&s.status.as_str()) {
        fail!("summary.status {:?} is not recognized", s.status);
    }
    if s.pairs < 0 {
        fail!("summary.pairs must not be negative");
    }
    if s.pairs != expected_pairs {
        fail!("summary.pairs is {}, want {expected_pairs}", s.pairs);
    }
    let values = [
        ("summary.control_mean", &s.control_mean),
        ("summary.treatment_mean", &s.treatment_mean),
        ("summary.delta", &s.delta),
        ("summary.ci95_lower", &s.ci95_lower),
        ("summary.ci95_upper", &s.ci95_upper),
    ];
    for (name, v) in values {
        if !v.is_empty() {
            validate_decimal(name, v)?;
        }
    }
    if s.status != STATUS_FAILED {
        if let Some((name, _)) = values.iter().find(|(_, v)| v.is_empty()) {
            fail!("{name} is required when summary.status is {:?}", s.status);
        }
    }
    Ok(())
}

// ============ Canonical JSON (Go's encoding/json with HTML escaping off) ============

/// Append `s` as a JSON string exactly as Go's encoder writes it with `SetEscapeHTML(false)`:
/// `"` and `\` escaped, control characters as `\b \f \n \r \t` or `\u00xx`, U+2028 and U+2029
/// always escaped, everything else (including DEL and `<>&`) literal.
fn push_str(out: &mut String, s: &str) {
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

/// A JSON object written field by field in declaration order, with Go's `omitempty` rule as an
/// explicit choice per field.
struct Obj<'a> {
    out: &'a mut String,
    first: bool,
}

impl<'a> Obj<'a> {
    fn new(out: &'a mut String) -> Self {
        out.push('{');
        Obj { out, first: true }
    }
    fn key(&mut self, k: &str) -> &mut String {
        if !self.first {
            self.out.push(',');
        }
        self.first = false;
        push_str(self.out, k);
        self.out.push(':');
        self.out
    }
    fn str(&mut self, k: &str, v: &str) {
        let out = self.key(k);
        push_str(out, v);
    }
    fn str_omitempty(&mut self, k: &str, v: &str) {
        if !v.is_empty() {
            self.str(k, v);
        }
    }
    fn raw(&mut self, k: &str, v: &str) {
        self.key(k).push_str(v);
    }
    fn strs(&mut self, k: &str, v: &[String]) {
        let out = self.key(k);
        out.push('[');
        for (i, s) in v.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            push_str(out, s);
        }
        out.push(']');
    }
    fn strs_omitempty(&mut self, k: &str, v: &[String]) {
        if !v.is_empty() {
            self.strs(k, v);
        }
    }
    fn end(self) {
        self.out.push('}');
    }
}

fn push_memory_ref(out: &mut String, m: &MemoryRef) {
    let mut o = Obj::new(out);
    o.str("chain_id", &m.chain_id);
    o.str("memory_id", &m.memory_id);
    o.str("content_hash", &m.content_hash);
    o.str("domain", &m.domain);
    o.str("author_agent_id", &m.author_agent_id);
    o.raw("classification", &m.classification.to_string());
    o.end();
}

fn push_list<T>(out: &mut String, items: &[T], f: impl Fn(&mut String, &T)) {
    out.push('[');
    for (i, item) in items.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        f(out, item);
    }
    out.push(']');
}

fn sorted_tasks(tasks: &[MemoryRef]) -> Vec<MemoryRef> {
    let mut sorted = tasks.to_vec();
    sorted.sort_by(|a, b| {
        (a.chain_id.as_bytes(), a.memory_id.as_bytes()).cmp(&(b.chain_id.as_bytes(), b.memory_id.as_bytes()))
    });
    sorted
}

/// The digest that must fill `task_set.digest`: SHA-256 of the versioned, sorted task list.
pub fn task_set_digest(tasks: &[MemoryRef]) -> String {
    let mut out = String::new();
    let mut o = Obj::new(&mut out);
    o.str("version", VERSION_V1);
    push_list(o.key("tasks"), &sorted_tasks(tasks), push_memory_ref);
    o.end();
    hex::encode(Sha256::digest(out.as_bytes()))
}

/// The canonical v1 body: the receipt validated, its set-like arrays sorted (tasks, runs, masked
/// ids, artifact hashes, evidence; context order is kept because it changes the model's input), and
/// every field written in the reference's order.
pub fn canonical_json(r: &Receipt) -> Result<String> {
    let times = validate(r)?;
    let mut out = String::new();
    let mut o = Obj::new(&mut out);
    o.str("version", &r.version);
    o.str("created_at", &format_time(times.created_at));
    {
        let mut p = Obj::new(o.key("producer"));
        p.str("name", &r.producer.name);
        p.str("version", &r.producer.version);
        p.str("implementation_hash", &r.producer.implementation_hash);
        p.end();
    }
    {
        let mut t = Obj::new(o.key("task_set"));
        t.str("id", &r.task_set.id);
        t.str("version", &r.task_set.version);
        t.str("digest", &r.task_set.digest);
        push_list(t.key("tasks"), &sorted_tasks(&r.task_set.tasks), push_memory_ref);
        t.end();
    }
    push_memory_ref(o.key("candidate"), &r.candidate);
    {
        let e = &r.evaluation;
        let mut ev = Obj::new(o.key("evaluation"));
        {
            let mut j = Obj::new(ev.key("judge"));
            j.str("model_id", &e.judge.model_id);
            j.str("model_hash", &e.judge.model_hash);
            j.str("rubric_hash", &e.judge.rubric_hash);
            j.str("prompt_hash", &e.judge.prompt_hash);
            j.str("environment_hash", &e.judge.environment_hash);
            j.end();
        }
        {
            let mut rp = Obj::new(ev.key("retrieval"));
            rp.str("id", &e.retrieval.id);
            rp.str("version", &e.retrieval.version);
            rp.raw("top_k", &e.retrieval.top_k.to_string());
            rp.end();
        }
        ev.str("metric", &e.metric);
        ev.str("unit", &e.unit);
        ev.raw(
            "higher_is_better",
            if e.higher_is_better { "true" } else { "false" },
        );
        ev.raw("repeats", &e.repeats.to_string());
        ev.raw("forced_context", if e.forced_context { "true" } else { "false" });
        ev.str("started_at", &format_time(times.started_at));
        ev.str("completed_at", &format_time(times.completed_at));
        ev.end();
    }
    let mut runs: Vec<Run> = r.runs.clone();
    for run in &mut runs {
        run.masked_memory_ids.sort();
        run.artifact_hashes.sort();
    }
    runs.sort_by(|a, b| {
        (a.task_memory_id.as_bytes(), a.trial, a.arm.as_bytes()).cmp(&(
            b.task_memory_id.as_bytes(),
            b.trial,
            b.arm.as_bytes(),
        ))
    });
    push_list(o.key("runs"), &runs, |out, run| {
        let mut x = Obj::new(out);
        x.str("task_memory_id", &run.task_memory_id);
        x.raw("trial", &run.trial.to_string());
        x.str("arm", &run.arm);
        x.raw("seed", &run.seed.to_string());
        x.str("query_hash", &run.query_hash);
        x.strs_omitempty("context_memory_ids", &run.context_memory_ids);
        x.strs_omitempty("masked_memory_ids", &run.masked_memory_ids);
        x.str_omitempty("score", &run.score);
        if let Some(p) = run.passed {
            x.raw("passed", if p { "true" } else { "false" });
        }
        if run.latency_micros != 0 {
            x.raw("latency_micros", &run.latency_micros.to_string());
        }
        x.strs_omitempty("artifact_hashes", &run.artifact_hashes);
        x.str_omitempty("error", &run.error);
        x.end();
    });
    {
        let s = &r.summary;
        let mut x = Obj::new(o.key("summary"));
        x.str("status", &s.status);
        x.raw("pairs", &s.pairs.to_string());
        x.str_omitempty("control_mean", &s.control_mean);
        x.str_omitempty("treatment_mean", &s.treatment_mean);
        x.str_omitempty("delta", &s.delta);
        x.str_omitempty("ci95_lower", &s.ci95_lower);
        x.str_omitempty("ci95_upper", &s.ci95_upper);
        x.end();
    }
    let mut evidence = r.evidence.clone();
    evidence.sort_by(|a, b| {
        (a.digest.as_bytes(), a.kind.as_bytes(), a.media_type.as_bytes()).cmp(&(
            b.digest.as_bytes(),
            b.kind.as_bytes(),
            b.media_type.as_bytes(),
        ))
    });
    push_list(o.key("evidence"), &evidence, |out, ev| {
        let mut x = Obj::new(out);
        x.str("kind", &ev.kind);
        x.str("media_type", &ev.media_type);
        x.str("digest", &ev.digest);
        x.str_omitempty("uri", &ev.uri);
        x.end();
    });
    o.strs_omitempty("caveats", &r.caveats);
    o.end();
    Ok(out)
}

/// SHA-256 of the canonical body, lowercase hex.
pub fn digest_hex(r: &Receipt) -> Result<String> {
    Ok(hex::encode(Sha256::digest(canonical_json(r)?.as_bytes())))
}

// ============ Signatures ============

fn decode_hex<const N: usize>(field: &str, v: &str) -> Result<[u8; N]> {
    if v.is_empty() {
        fail!("{field} is required");
    }
    if v != v.to_lowercase() {
        fail!("{field} must be lowercase hex");
    }
    let bytes = hex::decode(v).map_err(|e| Error(format!("decode {field}: {e}")))?;
    let n = bytes.len();
    bytes
        .try_into()
        .map_err(|_| Error(format!("{field} has {n} bytes, want {N}")))
}

/// Verify one detached signature: `Ed25519(VERSION_V1 || 0x00 || SHA-256(canonical body))`.
pub fn verify_signature(r: &Receipt, s: &Signature) -> Result<()> {
    if s.scheme != "ed25519" {
        fail!("unsupported signature scheme {:?}", s.scheme);
    }
    if !ROLES.contains(&s.role.as_str()) {
        fail!("signature role {:?} is not recognized", s.role);
    }
    validate_text("signature.signer_id", &s.signer_id)?;
    let public_key = decode_hex::<32>("public_key", &s.public_key)?;
    let signature = decode_hex::<64>("signature", &s.signature)?;
    if s.role == ROLE_SAGE_AGENT && s.signer_id != s.public_key {
        fail!("SAGE signer_id does not match public_key");
    }
    let mut message = Vec::with_capacity(VERSION_V1.len() + 33);
    message.extend_from_slice(VERSION_V1.as_bytes());
    message.push(0);
    message.extend_from_slice(&Sha256::digest(canonical_json(r)?.as_bytes()));
    let key = ed25519_dalek::VerifyingKey::from_bytes(&public_key)
        .map_err(|_| Error("signature verification failed".into()))?;
    key.verify_strict(&message, &ed25519_dalek::Signature::from_bytes(&signature))
        .map_err(|_| Error("signature verification failed".into()))
}

/// The reference `VerifyEnvelope`: a valid receipt, every signature valid, no duplicate signer, and
/// at least one evaluator signature.
pub fn verify(env: &SignedReceipt) -> Result<String> {
    validate(&env.receipt)?;
    if env.signatures.is_empty() {
        fail!("receipt has no signatures");
    }
    let mut seen = HashSet::new();
    for (i, s) in env.signatures.iter().enumerate() {
        verify_signature(&env.receipt, s).map_err(|e| Error(format!("signature {i}: {e}")))?;
        if !seen.insert((s.role.as_str(), s.signer_id.as_str(), s.public_key.as_str())) {
            fail!(
                "duplicate signature for role {:?} signer {:?}",
                s.role,
                s.signer_id
            );
        }
    }
    if !env.signatures.iter().any(|s| s.role == ROLE_EVALUATOR) {
        fail!("receipt has no evaluator signature");
    }
    digest_hex(&env.receipt)
}

// ============ The off-consensus label ============

/// What a valid receipt contributes to Noesis: an evidence record, kept outside consensus. Decimal
/// values stay strings, exactly as signed.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct Label {
    pub kind: String,
    pub receipt_digest: String,
    pub created_at: String,
    pub candidate: LabelMemory,
    pub task_set: LabelTaskSet,
    pub metric: String,
    pub unit: String,
    pub higher_is_better: bool,
    pub forced_context: bool,
    pub repeats: i64,
    pub pairs: i64,
    pub status: String,
    pub control_mean: String,
    pub treatment_mean: String,
    pub delta: String,
    pub ci95_lower: String,
    pub ci95_upper: String,
    pub judge_model_id: String,
    pub judge_model_hash: String,
    pub producer: String,
    pub signers: Vec<LabelSigner>,
    pub independence: Independence,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct LabelMemory {
    pub chain_id: String,
    pub memory_id: String,
    pub content_hash: String,
    pub author_agent_id: String,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct LabelTaskSet {
    pub id: String,
    pub version: String,
    pub digest: String,
    pub tasks: usize,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct LabelSigner {
    pub role: String,
    pub signer_id: String,
    pub public_key: String,
}

/// Facts a trusted-evaluator policy needs, recorded but not judged here. An evaluator key equal to
/// the candidate's or a task's author key means the work was graded by its own author.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct Independence {
    pub evaluator_is_candidate_author: bool,
    pub evaluator_is_task_author: bool,
    pub task_authors: usize,
}

/// Verify an envelope and build its label. Fails with the first broken rule.
pub fn verify_to_label(data: &[u8]) -> Result<Label> {
    let env = decode(data)?;
    let digest = verify(&env)?;
    let r = &env.receipt;
    let times = validate(r)?;
    let evaluators: Vec<&str> = env
        .signatures
        .iter()
        .filter(|s| s.role == ROLE_EVALUATOR)
        .map(|s| s.public_key.as_str())
        .collect();
    let task_authors: HashSet<&str> = r
        .task_set
        .tasks
        .iter()
        .map(|t| t.author_agent_id.as_str())
        .collect();
    Ok(Label {
        kind: VERSION_V1.into(),
        receipt_digest: digest,
        created_at: format_time(times.created_at),
        candidate: LabelMemory {
            chain_id: r.candidate.chain_id.clone(),
            memory_id: r.candidate.memory_id.clone(),
            content_hash: r.candidate.content_hash.clone(),
            author_agent_id: r.candidate.author_agent_id.clone(),
        },
        task_set: LabelTaskSet {
            id: r.task_set.id.clone(),
            version: r.task_set.version.clone(),
            digest: r.task_set.digest.clone(),
            tasks: r.task_set.tasks.len(),
        },
        metric: r.evaluation.metric.clone(),
        unit: r.evaluation.unit.clone(),
        higher_is_better: r.evaluation.higher_is_better,
        forced_context: r.evaluation.forced_context,
        repeats: r.evaluation.repeats,
        pairs: r.summary.pairs,
        status: r.summary.status.clone(),
        control_mean: r.summary.control_mean.clone(),
        treatment_mean: r.summary.treatment_mean.clone(),
        delta: r.summary.delta.clone(),
        ci95_lower: r.summary.ci95_lower.clone(),
        ci95_upper: r.summary.ci95_upper.clone(),
        judge_model_id: r.evaluation.judge.model_id.clone(),
        judge_model_hash: r.evaluation.judge.model_hash.clone(),
        producer: format!(
            "{} {} ({})",
            r.producer.name, r.producer.version, r.producer.implementation_hash
        ),
        signers: env
            .signatures
            .iter()
            .map(|s| LabelSigner {
                role: s.role.clone(),
                signer_id: s.signer_id.clone(),
                public_key: s.public_key.clone(),
            })
            .collect(),
        independence: Independence {
            evaluator_is_candidate_author: evaluators.contains(&r.candidate.author_agent_id.as_str()),
            evaluator_is_task_author: evaluators.iter().any(|k| task_authors.contains(k)),
            task_authors: task_authors.len(),
        },
    })
}

