//! Verifier for SAGE outcome receipts, v1 (`sage.noesis.outcome-receipt/v1`).
//!
//! An outcome receipt is SAGE's signed record of paired control and treatment runs that measure
//! whether one public memory changed task outcomes under a pinned judge. The reference is SAGE's own
//! code (github.com/l33tdawg/sage, `internal/outcomereceipt`, design doc
//! `docs/design/noesis-outcome-receipts.md`); this crate checks a receipt the way the reference does,
//! computing the same canonical bytes and digest, and turns a valid one into an off-consensus
//! [`Label`] for Noesis: evidence for the
//! calibration measure and the learned judge, never an input to consensus. Nothing in `node` depends
//! on this crate, so a receipt cannot reach standing or finality (the fence in ARCHITECTURE.md).
//!
//! Parity is tested against vectors generated by SAGE's Go code (`tests/vectors/`). The verifier is
//! deliberately stricter than the reference in four places, each failing closed: object keys must
//! match exactly (Go matches them case-insensitively), JSON `null` is rejected where a value is
//! expected (Go reads it as empty), invalid UTF-8 and lone surrogates are rejected (Go replaces them),
//! and Ed25519 signatures are checked with `verify_strict` (Go also accepts small-order keys). A
//! receipt written by SAGE's own tooling uses none of these.
//!
//! Honest floor: a valid receipt proves that the named evaluator key signed these numbers. It does
//! not prove the evaluator is independent of the memory's author, that the task set is honest, or
//! that the judge is any good. The label records the facts a written evaluator policy needs to decide
//! that ([`Independence`]); deciding it is the consumer's job, as the design doc says.

