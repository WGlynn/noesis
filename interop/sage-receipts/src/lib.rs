    #[test]
    fn times_parse_and_print_as_the_reference_does() {
        let p = |s| parse_time("t", s).map(|(t, utc)| (format_time(t), utc));
        assert_eq!(
            p("2026-10-26T08:05:00Z"),
            Ok(("2026-10-26T08:05:00Z".into(), true))
        );
        assert_eq!(
            p("2026-10-26T08:05:00.120000Z"),
            Ok(("2026-10-26T08:05:00.12Z".into(), true))
        );
        assert_eq!(
            p("2026-10-26T08:05:00,5Z"),
            Ok(("2026-10-26T08:05:00.5Z".into(), true))
        );
        assert_eq!(
            p("2026-10-26T08:05:00.1234567891Z"),
            Ok(("2026-10-26T08:05:00.123456789Z".into(), true))
        );
        assert_eq!(
            p("2026-10-26T8:05:00Z"),
            Ok(("2026-10-26T08:05:00Z".into(), true))
        );
        assert_eq!(
            p("2026-10-26T08:05:00+00:00"),
            Ok(("2026-10-26T08:05:00Z".into(), false))
        );
        assert_eq!(
            p("2026-10-26T10:05:00+02:00"),
            Ok(("2026-10-26T08:05:00Z".into(), false))
        );
        assert_eq!(
            p("2024-02-29T00:00:00Z"),
            Ok(("2024-02-29T00:00:00Z".into(), true))
        );
        assert_eq!(
            p("0005-01-01T00:00:00Z"),
            Ok(("0005-01-01T00:00:00Z".into(), true))
        );
        for bad in [
            "2026-10-26t08:05:00Z",
            "2026-10-26T08:05:00z",
            "2026-10-26T08:05:60Z",
            "2025-02-29T00:00:00Z",
            "2026-13-01T00:00:00Z",
            "2026-10-26T08:05Z",
            "2026-10-26T08:05:00",
            "2026-10-26T08:05:00.Z",
        ] {
            assert!(parse_time("t", bad).is_err(), "{bad}");
        }
        assert!(
            utc_time("t", "0001-01-01T00:00:00Z").is_err(),
            "the reference's zero time counts as missing"
        );
    }

