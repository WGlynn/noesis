    #[test]
    fn decoding_rejects_duplicates_depth_and_trailing_values() {
        assert!(decode(br#"{"receipt":{},"receipt":{},"signatures":[]}"#)
            .unwrap_err()
            .0
            .contains("duplicate key"));
        assert!(decode(br#"{"receipt":{},"signatures":[]} {}"#)
            .unwrap_err()
            .0
            .contains("trailing JSON value"));
        assert!(decode(br#"{"receipt":{},"signatures":[],"unexpected":true}"#)
            .unwrap_err()
            .0
            .contains("unknown field"));
        let deep = format!("{{\"x\":{}{}}}", "[".repeat(70), "]".repeat(70));
        assert!(decode(deep.as_bytes())
            .unwrap_err()
            .0
            .contains("nesting exceeds 64"));
        let ok_depth = format!("{{\"x\":{}{}}}", "[".repeat(63), "]".repeat(63));
        assert!(
            !decode(ok_depth.as_bytes()).unwrap_err().0.contains("nesting"),
            "63 levels under the root are allowed"
        );
        assert!(decode(b"{\"receipt\":{\"version\":\"\xff\"}}")
            .unwrap_err()
            .0
            .contains("invalid UTF-8"));
    }
